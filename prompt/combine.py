# combine.py，合并新旧知识点的提示词。
# 输入：
# - old_note: str (旧笔记内容)
# - new_knowledge: str (新知识点内容)
# 输出：
# - prompt_: str (合并提示词)
def combine_prompt(old_note: str, new_knowledge: str) -> str:
    prompt_ = f"""你是一个专业的知识点整合助手。请将以下**旧笔记**与**新知识点**进行整合，生成一份新的 Markdown 文档。

### 旧笔记
{old_note}

### 新知识点
{new_knowledge}

### 整合规则（严格遵循）
1. **无关判断**：如果新知识点与旧笔记内容完全无关（例如主题、领域完全不同），只输出 **KEEP**（不要加其他内容）。否则，必须进行融合。
2. **融合原则**：
   - 保留旧笔记的核心结构（如分节标题、示例、注意事项等）。
   - 将新知识点作为补充内容，**自然地插入**到旧笔记的合适位置（例如在“定义”后补充新定义，在“示例”中添加新例子，或新增一个小节）。
   - 如果新知识点提供了新的视角或更优的解释，可以适当改写旧笔记的对应部分，但必须保留所有重要信息。
   - 删除重复内容，合并同类信息，使文档逻辑更连贯。
3. **输出格式**：
   - 必须包含合法的 YAML front matter（`---` 包围），包含 `title`、`summary`、`tags` 三个字段。
   - 标题和摘要应根据**融合后的最终内容**重新生成，要能概括全篇。
   - 正文使用标准 Markdown 格式，保持原有层次（如 `## 定义`、`## 示例` 等）。
   - **不要用代码块包裹整个输出**，直接输出纯文本。

### 输出格式示例（仅作格式参考，具体内容需根据实际融合结果调整）
---
title: 融合后的新标题
summary: 融合后的摘要，概括旧笔记与新知识点
tags: [标签1, 标签2, 标签3]
---
# 融合后的新标题

## 定义（保留旧笔记的定义，若新知识点有补充则整合）
...

## 原理/特性（保留旧笔记，同时加入新知识点的扩展）
...

## 示例（保留旧笔记示例，添加新知识点示例或替换更优示例）
...

## 注意事项（整合双方的注意事项，避免重复）
...

### 新知识点新增的章节（如果必要）
...
"""
    return prompt_

