#整理提示词
def arrange_prompt(cleaned_text: str) -> str:
    prompt_ = f"""你是一个专业的知识点整理助手。请将以下文本整理成结构化的知识点，输出格式为 YAML front matter + Markdown 正文。

### 输出格式要求
必须以以下格式输出，不要包含任何额外解释：
---
title: 标题
summary: 摘要
tags: [标签1, 标签2, 标签3]
---
# 标题
正文内容（Markdown格式）

### 各部分具体要求
- **标题**：用 5-15 字概括核心知识点，简洁有力，类似文章标题。
- **摘要**：用 50-100 字概括核心内容，包含关键信息，但不展开细节。
- **标签**：提取 3-5 个关键词，用英文逗号分隔，放在列表中。标签应反映知识点的领域、技术、概念等，如 ["Python", "闭包", "函数式编程"]。
- **正文**：用 Markdown 格式详细阐述知识点，要求：
  - 使用二级标题（##）分点，如「定义」「原理」「示例」「注意事项」等。
  - 保留技术细节，必要时用代码块（```）展示示例。
  - 语言清晰，逻辑连贯。

### 待处理文本
{cleaned_text}

现在，请开始输出。"""
    return prompt_